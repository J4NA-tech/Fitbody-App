class WorkoutLog {
  final String name;
  final int duration;
  final String difficulty;
  final int calories;
  final int exerciseCount;
  final DateTime date;

  WorkoutLog({
    required this.name,
    required this.duration,
    required this.difficulty,
    required this.calories,
    required this.exerciseCount,
    required this.date,
  });
}
